create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid()
  );
$$;

grant execute on function public.is_current_user_admin() to anon, authenticated;

-- Public event-registration counts. It never exposes people's details.
create or replace view public.event_registration_counts
as
select
  e.id as event_id,
  count(r.id)::integer as registered
from public.events e
left join public.registrations r
  on r.event_id = e.id and r.payment_status <> 'cancelled'
group by e.id;

grant select on public.event_registration_counts to anon, authenticated;

