create extension if not exists pgcrypto;

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  date date not null,
  time text not null,
  location text not null,
  purpose text not null,
  dress text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  capacity integer not null default 100 check (capacity > 0),
  status text not null default 'active' check (status in ('active','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null,
  phone text not null,
  source text,
  event_id uuid not null references public.events(id) on delete restrict,
  amount numeric(12,2) not null default 0,
  payment_method text not null default 'bank_transfer' check (payment_method in ('bank_transfer','payoneer')),
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','verified','cancelled')),
  ticket_code text not null unique,
  ticket_lookup_token uuid not null unique default gen_random_uuid(),
  ticket_status text not null default 'valid' check (ticket_status in ('valid','used','cancelled')),
  checked_in_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  type text not null default 'image' check (type in ('image','video')),
  media_url text not null,
  storage_path text,
  title text not null,
  description text,
  memory_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
