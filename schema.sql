-- Atomically create a registration and ticket.
create or replace function public.register_for_event(
  p_first_name text,
  p_last_name text,
  p_email text,
  p_phone text,
  p_source text,
  p_event_id uuid
)
returns table (
  id bigint,
  ticket_code text,
  ticket_lookup_token uuid,
  payment_status text,
  amount numeric,
  event_name text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  e public.events%rowtype;
  current_count integer;
  code text;
  new_id bigint;
  new_token uuid;
  status_value text;
begin
  if length(trim(coalesce(p_first_name,''))) < 1
     or length(trim(coalesce(p_last_name,''))) < 1
     or length(trim(coalesce(p_email,''))) < 3
     or length(trim(coalesce(p_phone,''))) < 5 then
    raise exception 'Please complete all required fields.';
  end if;

  select * into e
  from public.events
  where id = p_event_id and status = 'active'
  for update;

  if not found then
    raise exception 'Event not found or no longer active.';
  end if;

  select count(*)::integer into current_count
  from public.registrations
  where event_id = e.id and payment_status <> 'cancelled';

  if current_count >= e.capacity then
    raise exception 'This event is now full.';
  end if;

  code := 'PG-' || to_char(current_date, 'YYYY') || '-' ||
          upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
  new_token := gen_random_uuid();
  status_value := case when e.price = 0 then 'paid' else 'pending' end;

  insert into public.registrations(
    first_name,last_name,email,phone,source,event_id,amount,
    payment_method,payment_status,ticket_code,ticket_lookup_token,ticket_status
  )
  values(
    trim(p_first_name),trim(p_last_name),lower(trim(p_email)),trim(p_phone),
    nullif(trim(coalesce(p_source,'')),''),e.id,e.price,'bank_transfer',
    status_value,code,new_token,'valid'
  )
  returning registrations.id into new_id;

  return query select new_id,code,new_token,status_value,e.price,e.name;
end;
$$;

grant execute on function public.register_for_event(text,text,text,text,text,uuid) to anon, authenticated;

-- Public ticket retrieval uses an unguessable token, not the numeric database ID.
create or replace function public.get_ticket_by_token(p_token uuid)
returns table (
  id bigint,
  first_name text,
  last_name text,
  email text,
  event_name text,
  event_date date,
  event_time text,
  location text,
  dress text,
  amount numeric,
  payment_status text,
  ticket_code text,
  ticket_status text,
  checked_in_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select r.id,r.first_name,r.last_name,r.email,e.name,e.date,e.time,e.location,e.dress,
         r.amount,r.payment_status,r.ticket_code,r.ticket_status,r.checked_in_at
  from public.registrations r
  join public.events e on e.id=r.event_id
  where r.ticket_lookup_token = p_token;
$$;

grant execute on function public.get_ticket_by_token(uuid) to anon, authenticated;

-- Verify bank transfer. Only an admin can do this.
create or replace function public.verify_registration_payment(p_registration_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_current_user_admin() then
    raise exception 'Admin access required.';
  end if;

  update public.registrations
  set payment_status='verified',
      ticket_status=case when ticket_status='cancelled' then ticket_status else 'valid' end
  where id=p_registration_id
    and payment_status <> 'cancelled';

  if not found then
    raise exception 'Registration not found or already cancelled.';
  end if;
  return true;
end;
$$;

grant execute on function public.verify_registration_payment(bigint) to authenticated;

-- Atomic, single-use event-day scan.
create or replace function public.scan_ticket(p_ticket_code text)
returns table (
  id bigint,
  first_name text,
  last_name text,
  event_name text,
  ticket_code text,
  ticket_status text,
  checked_in_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.registrations%rowtype;
  stamp timestamptz := now();
begin
  if not public.is_current_user_admin() then
    raise exception 'Admin access required.';
  end if;

  select * into r
  from public.registrations
  where ticket_code=upper(trim(p_ticket_code))
  for update;

  if not found then
    raise exception 'Ticket not found.';
  end if;

  if r.payment_status not in ('paid','verified') then
    raise exception 'Payment has not been verified yet.';
  end if;

  if r.ticket_status='cancelled' then
    raise exception 'This ticket has been cancelled.';
  end if;

  if r.ticket_status='used' then
    raise exception 'Ticket already used on %.', to_char(r.checked_in_at at time zone 'Africa/Lagos','DD Mon YYYY, HH12:MI AM');
  end if;

  update public.registrations
  set ticket_status='used', checked_in_at=stamp
  where id=r.id and ticket_status='valid';

  return query
  select r.id,r.first_name,r.last_name,e.name,r.ticket_code,'used'::text,stamp
  from public.events e where e.id=r.event_id;
end;
$$;

grant execute on function public.scan_ticket(text) to authenticated;

